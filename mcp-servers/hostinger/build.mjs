#!/usr/bin/env node
// Generates src/catalog.mjs (server data) and the plugin skill catalog from the
// Hostinger OpenAPI spec. Zero dependencies. Usage:
//   node build.mjs                 # fetch the live spec
//   node build.mjs path/to/openapi.json
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SPEC_URL = 'https://developers.hostinger.com/openapi/openapi.json';
const SKILL_DIR = join(HERE, '../../plugins/ntxp-hostinger/skills/hostinger/references');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// POST operations that change nothing on the account.
const SAFE_POST = /validate|availability|suggest|generateUploadURL|checkIf|detect|verifyDomainOwnership/i;
const MONEY = /purchase|renew|createPurchaseOrder|enableAutoRenewal|claimFree|startDomainTransfer/i;
const DESTRUCTIVE = /^delete|delete|reset|restore|recreate|deploy|import|uninstall|remove|stop|cancel|reject|disable|purge|clear/i;

const src = process.argv[2];
const spec = JSON.parse(src ? await readFile(src, 'utf8') : await (await fetch(SPEC_URL)).text());

const DROP = new Set(['example', 'examples', 'x-scalar-ignore', 'x-optic-ignore-example', 'xml', 'externalDocs']);
function deref(node, depth = 0) {
  if (Array.isArray(node)) return node.map((v) => deref(v, depth));
  if (!node || typeof node !== 'object') return node;
  if (node.$ref) {
    if (depth > 10) return {};
    const target = node.$ref.replace(/^#\//, '').split('/').reduce((o, k) => o?.[k], spec);
    return deref(target ?? {}, depth + 1);
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) if (!DROP.has(k)) out[k] = deref(v, depth);
  return out;
}
const clip = (s, n) => {
  const t = String(s ?? '').replace(/\s+/g, ' ').trim();
  return t.length > n ? t.slice(0, n - 1) + '…' : t;
};
const kind = (id, method) => {
  const name = id.replace(/^[^_]+_/, '');
  if (method === 'get' || (method === 'post' && SAFE_POST.test(name))) return 'r';
  if (MONEY.test(name)) return '$';
  if (method === 'delete' || DESTRUCTIVE.test(name)) return 'd';
  return 'w';
};

const ops = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const raw = item[method];
    if (!raw?.operationId) continue;
    const op = deref(raw);
    const params = [...(deref(item.parameters) ?? []), ...(op.parameters ?? [])];
    const body = op.requestBody?.content?.['application/json']?.schema;
    const props = {};
    const required = [];
    const where = {};
    const add = (name, schema, loc, req) => {
      if (props[name]) return; // path and query win over a body field of the same name
      props[name] = schema;
      where[name] = loc;
      if (req) required.push(name);
    };
    for (const p of params) {
      if (p.in !== 'path' && p.in !== 'query') continue;
      const schema = { ...(p.schema ?? { type: 'string' }) };
      if (p.description) schema.description = p.description;
      add(p.name, schema, p.in === 'path' ? 'p' : p.explode === false ? 'c' : 'q', p.in === 'path' || p.required);
    }
    let wholeBody = false;
    if (body) {
      if (body.type === 'object' || body.properties) {
        for (const [name, schema] of Object.entries(body.properties ?? {})) {
          add(name, schema, 'b', (body.required ?? []).includes(name));
        }
      } else {
        wholeBody = true;
        add('body', body, 'B', op.requestBody.required);
      }
    }
    ops[op.operationId] = {
      m: method.toUpperCase(),
      p: path,
      g: op.tags?.[0] ?? 'Other',
      s: clip(op.summary, 120),
      d: clip(op.description, 600),
      k: kind(op.operationId, method),
      ...(op.deprecated ? { x: 1 } : {}),
      w: where,
      i: { type: 'object', properties: props, ...(required.length ? { required } : {}) },
      ...(wholeBody ? { B: 1 } : {}),
    };
  }
}

const version = spec.info.version;
const count = Object.keys(ops).length;
await writeFile(
  join(HERE, 'src/catalog.mjs'),
  `// GENERATED by build.mjs from the Hostinger OpenAPI spec ${version}. Do not edit.\n` +
    `export const SPEC_VERSION = ${JSON.stringify(version)};\n` +
    `export const OPS = ${JSON.stringify(ops)};\n`,
);

// Skill catalog: one file per product area, loaded only when that area is needed.
const AREA = (g) => {
  const a = g.split(':')[0].trim().toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return a === 'domain-access-verifier' || a === 'agent-readiness' || a === 'gpu' || a === 'horizons' ? 'other' : a;
};
const MARK = { r: 'read', w: 'write', d: 'DESTRUCTIVE', $: 'SPENDS MONEY' };
const areas = {};
for (const [id, op] of Object.entries(ops)) ((areas[AREA(op.g)] ??= {})[op.g] ??= []).push([id, op]);
const outDir = join(SKILL_DIR, 'catalog');
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
const index = [];
for (const area of Object.keys(areas).sort()) {
  let md = `# Hostinger operations: ${area}\n\nGenerated from Hostinger API spec ${version}. Run any row with \`hostinger_call\`. Get the argument schema first with \`hostinger_describe\`.\n`;
  let n = 0;
  for (const tag of Object.keys(areas[area]).sort()) {
    md += `\n## ${tag}\n\n| Operation | Class | What it does |\n|---|---|---|\n`;
    for (const [id, op] of areas[area][tag]) {
      md += `| \`${id}\` | ${MARK[op.k]} | ${op.s.replace(/\|/g, '/')}${op.x ? ' (deprecated)' : ''} |\n`;
      n++;
    }
  }
  await writeFile(join(outDir, `${area}.md`), md);
  index.push({ area, n, tags: Object.keys(areas[area]).sort().map((t) => t.split(':').pop().trim()) });
}
await writeFile(
  join(SKILL_DIR, 'catalog-index.md'),
  `# Operation catalog index\n\nGenerated from Hostinger API spec ${version}: ${count} operations. Read only the one area file the task needs.\n\n| Area file | Operations | Covers |\n|---|---|---|\n` +
    index.map((r) => `| \`catalog/${r.area}.md\` | ${r.n} | ${r.tags.join(', ')} |`).join('\n') +
    '\n',
);
console.log(`spec ${version}: ${count} operations, ${index.length} area files`);
